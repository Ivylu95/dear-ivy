// The thresholds the harness enforces, read out of the rows that state them.
//
//   node scripts/thresholds.mjs           write both files from the registers
//   node scripts/thresholds.mjs --check   fail if either file and the registers disagree
//
// FND-009, "Every threshold the system enforces is stated once, beside the
// reason for it, and all of them can be read in one place." The number lives in
// the design column of the row it serves, as a marker of one fixed form
// (dev/specs/README.md § Thresholds):
//
//   `threshold scratch.ceiling = 100 MB`
//
// Two files come out of it, and both ship where the registers do not (ARC-007):
// .claude/thresholds.json, which the code reads (.claude/hooks/lib/thresholds.mjs),
// and .claude/THRESHOLDS.md, the one table a person reads. The check keeps all
// three one fact: edit the row, regenerate, commit together. In a copy without
// the registers there is nothing to compare, and the check passes.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SPECS_DIR } from '../../.claude/hooks/lib/paths.mjs';
import { walkFiles } from '../lib/walk-skip.mjs';
import { parseRows } from '../../.claude/hooks/lib/spec-rows.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const jsonOut = join(root, '.claude', 'thresholds.json');
const pageOut = join(root, '.claude', 'THRESHOLDS.md');
const MARKER = /`threshold ([a-z][A-Za-z0-9]*(?:\.[a-z][A-Za-z0-9]*)+) = (\d+(?:\.\d+)?) ([A-Za-z]+)`/g;

const specs = join(root, SPECS_DIR);
if (!existsSync(specs)) {
  console.log('thresholds: no registers in this copy, the shipped files stand');
  process.exit(0);
}

const registers = walkFiles(specs, { names: new Set(), keep: (n) => n.endsWith('.md') });

const thresholds = {};
const rows = {};
const faults = [];
for (const file of registers.sort()) {
  for (const { id, statement, design } of parseRows(readFileSync(file, 'utf8'))) {
    for (const [, key, value, unit] of design.matchAll(MARKER)) {
      if (thresholds[key]) {
        faults.push(`${key} is stated by both ${thresholds[key].row} and ${id}; one home only`);
        continue;
      }
      thresholds[key] = { value: Number(value), unit, row: id };
      rows[id] = { statement, file: relative(root, file).replace(/\\/g, '/') };
    }
  }
}

if (faults.length) {
  console.error(`THRESHOLDS CHECK FAILED\n\n${faults.map((f) => `  - ${f}`).join('\n')}`);
  process.exit(1);
}

const keys = Object.keys(thresholds).sort();
const json = `${JSON.stringify(
  {
    _what: 'Generated by ux/scripts/thresholds.mjs from the threshold markers in the registers (FND-009). Edit the row, then regenerate; never edit this file.',
    thresholds: Object.fromEntries(keys.map((k) => [k, thresholds[k]])),
  },
  null,
  2,
)}\n`;

// Three narrow columns, so the table reads on a phone without scrolling sideways.
const page = [
  '<!-- Generated by ux/scripts/thresholds.mjs from the threshold markers in the registers (FND-009). Do not edit by hand. -->',
  '',
  '# Thresholds',
  '',
  'Every number past which the system acts: deletes, warns, flags or retries. Each is set in the spec row named beside it, with the reason, and only there; to change one, change the row and run `node ux/scripts/thresholds.mjs`.',
  '',
  '| Threshold | Value | Row |',
  '| --- | --- | --- |',
  ...keys.map((k) => `| \`${k}\` | ${thresholds[k].value} ${thresholds[k].unit} | ${thresholds[k].row} |`),
  '',
  '## The rows',
  '',
  ...Object.keys(rows)
    .sort()
    .map((id) => `- **${id}** · ${rows[id].statement} · \`${rows[id].file}\``),
  '',
].join('\n');

const same = (path, text) => existsSync(path) && readFileSync(path, 'utf8').replace(/\r\n/g, '\n') === text;

if (process.argv.includes('--check')) {
  const stale = [jsonOut, pageOut].filter((p, i) => !same(p, [json, page][i]));
  if (stale.length) {
    console.error(
      `THRESHOLDS CHECK FAILED\n\n${stale.map((p) => `  - ${relative(root, p).replace(/\\/g, '/')} does not match the registers.`).join('\n')} Run: node ux/scripts/thresholds.mjs`,
    );
    process.exit(1);
  }
  console.log(`thresholds check: ${keys.length} threshold(s), both files match the registers`);
  process.exit(0);
}

writeFileSync(jsonOut, json);
writeFileSync(pageOut, page);
console.log(`thresholds: wrote ${keys.length} threshold(s) to .claude/thresholds.json and .claude/THRESHOLDS.md`);
