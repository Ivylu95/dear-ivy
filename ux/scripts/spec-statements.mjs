// Every spec row's statement, by ID, for the reply check that runs without the
// registers.
//
//   node scripts/spec-statements.mjs           write .claude/spec-statements.json (and its parts)
//   node scripts/spec-statements.mjs --check   fail if the files and the registers disagree
//
// One row a line, it grows with the registers, so it cuts itself before the one-read
// line (E-031, lib/one-read.mjs, T-768): the first part keeps the name every reader
// knows, and the rows past PART_LINES go on in .claude/spec-statements/2.json, 3.json…,
// a folder so the release manifest withholds every part with one entry.
//
// WKB-007: a development reply on the spec step cites each row by its ID and
// its own words, and .claude/hooks/lib/dev-reply.mjs checks the words are the
// row's. It used to read dev/specs/ to do so, which ARC-008 forbids: the harness
// never reads the design while it runs. So the statements are carried here, in
// the harness, like the thresholds (thresholds.mjs, whose shape this follows).
//
// Unlike thresholds.json, this file is the design's own wording, and never ships
// (ARC-007; dev/skills/release/manifest.json lists it under `never`). In a copy
// without it the reply check holds the citation's shape alone; in a copy without
// the registers there is nothing to compare, and the check passes.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SPECS_DIR } from '../../.claude/hooks/lib/paths.mjs';
import { walkFiles } from '../lib/walk-skip.mjs';
import { parseRows } from '../../.claude/hooks/lib/spec-rows.mjs';
import { packParts } from '../../.claude/hooks/lib/one-read.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, '.claude', 'spec-statements.json');
const partsDir = join(root, '.claude', 'spec-statements');
/** Part n's file: the first keeps its name, the rest are numbered in the folder beside it. */
const partFile = (n) => (n === 1 ? out : join(partsDir, `${n}.json`));

const specs = join(root, SPECS_DIR);
if (!existsSync(specs)) {
  console.log('spec statements: no registers in this copy, nothing to compare');
  process.exit(0);
}

const registers = walkFiles(specs, { names: new Set(), keep: (n) => n.endsWith('.md') });

// Only a row the shared parser reads (a `| **ID** |` line or a `### ID · name`
// section) counts; an ID cited in prose, or written plainly under Recently
// deleted, never matches. An ID heading two rows
// has no one statement to carry, so it fails, as thresholds.mjs does.
const statements = {};
const homes = {};
const faults = [];
for (const file of registers.sort()) {
  const where = relative(root, file).replace(/\\/g, '/');
  for (const { id, statement } of parseRows(readFileSync(file, 'utf8'))) {
    if (id in statements) faults.push(`${id} heads a row in both ${homes[id]} and ${where}; one home only`);
    else [statements[id], homes[id]] = [statement, where];
  }
}
if (faults.length) {
  console.error(`SPEC STATEMENTS CHECK FAILED\n\n${faults.map((f) => `  - ${f}`).join('\n')}`);
  process.exit(1);
}

const render = (n, ids) => `${JSON.stringify(
  {
    _what: `Generated by ux/scripts/spec-statements.mjs from the registers (WKB-007, ARC-008). Read by .claude/hooks/lib/dev-reply.mjs. Never shipped (ARC-007). Edit the row, then regenerate; never edit this file.${n > 1 ? ` Part ${n}: the rows go on from part ${n - 1}, each part within one read.` : ''}`,
    statements: Object.fromEntries(ids.map((id) => [id, statements[id]])),
  },
  null,
  2,
)}\n`;
const want = new Map(packParts(Object.keys(statements).sort(), render).map(([n, ids]) => [partFile(n), render(n, ids)]));
const extra = existsSync(partsDir) ? readdirSync(partsDir).filter((f) => f.endsWith('.json')).map((f) => join(partsDir, f)).filter((f) => !want.has(f)) : [];
const shown = (f) => relative(root, f).replace(/\\/g, '/');

if (process.argv.includes('--check')) {
  const off = [...[...want].filter(([f, json]) => !existsSync(f) || readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== json).map(([f]) => f), ...extra];
  if (off.length) {
    console.error(`SPEC STATEMENTS CHECK FAILED\n\n  - ${off.map(shown).join(', ')} ${off.length === 1 ? 'does' : 'do'} not match the registers. Run: node ux/scripts/spec-statements.mjs`);
    process.exit(1);
  }
  console.log(`spec statements: ${Object.keys(statements).length} rows in ${want.size} part(s), in step with the registers`);
} else {
  for (const f of extra) rmSync(f);
  if (want.size > 1) mkdirSync(partsDir, { recursive: true });
  for (const [f, json] of want) writeFileSync(f, json);
  console.log(`spec statements: wrote ${Object.keys(statements).length} rows to ${[...want.keys()].map(shown).join(', ')}`);
}
